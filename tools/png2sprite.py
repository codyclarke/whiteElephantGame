"""Converts every PNG under assets/ into C++ sprite data the game links in.

The build runs this automatically, so you never need to run it by hand:
save a PNG, rebuild, and it's in the game.

Naming:
  assets/guests/manager_f4.png  ->  sprite "guests/manager", 4 frames side by side
  assets/couch.png              ->  sprite "couch", 1 frame
Pixels with alpha below 128 are transparent in the game.

Usage: python png2sprite.py ASSETS_DIR OUTPUT_CPP
"""

import pathlib
import re
import sys

from PIL import Image

TRANSPARENT_KEY = 0xF81F  # must match gfx::TRANSPARENT_KEY


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def convert(path, root):
    rel = path.relative_to(root).with_suffix("").as_posix()
    match = re.match(r"^(.*)_f(\d+)$", rel)
    name, frames = (match.group(1), int(match.group(2))) if match else (rel, 1)

    img = Image.open(path).convert("RGBA")
    width, height = img.size
    if frames < 1 or width % frames:
        sys.exit(f"{path}: width {width} isn't a multiple of {frames} frames")

    src = img.load()
    pixels = []
    for y in range(height):
        for x in range(width):
            r, g, b, a = src[x, y]
            if a < 128:
                pixels.append(TRANSPARENT_KEY)
            else:
                c = rgb565(r, g, b)
                if c == TRANSPARENT_KEY:
                    c ^= 1  # real magenta: nudge it so it doesn't vanish
                pixels.append(c)
    return name, width // frames, height, frames, pixels


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])

    sprites = [convert(p, root) for p in sorted(root.rglob("*.png"))]
    names = [s[0] for s in sprites]
    for name in sorted({n for n in names if names.count(n) > 1}):
        sys.exit(f"Two PNGs make the sprite \"{name}\" (e.g. {name}.png and {name}_f2.png). Delete one.")

    lines = [
        "// Generated by tools/png2sprite.py from assets/. Do not edit.",
        '#include "game/sprites.h"',
        "",
        "namespace {",
    ]
    for i, (name, w, h, frames, pixels) in enumerate(sprites):
        lines.append(f"// {name}: {w}x{h}, {frames} frame(s)")
        lines.append(f"const uint16_t PX_{i}[] = {{")
        for row in range(0, len(pixels), 16):
            lines.append("    " + ", ".join(f"0x{p:04X}" for p in pixels[row:row + 16]) + ",")
        lines.append("};")
    lines.append("}  // namespace")
    lines.append("")

    if sprites:
        lines.append("extern const Sprite SPRITES[] = {")
        for i, (name, w, h, frames, _) in enumerate(sprites):
            lines.append(f'    {{"{name}", {w}, {h}, {frames}, PX_{i}}},')
        lines.append("};")
    else:
        lines.append('extern const Sprite SPRITES[] = {{"", 0, 0, 0, nullptr}};')
    lines.append(f"extern const int SPRITE_COUNT = {len(sprites)};")
    text = "\n".join(lines) + "\n"

    # Only touch the file when something changed, so the game doesn't rebuild for nothing.
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    print(f"png2sprite: {len(sprites)} sprite(s)")


if __name__ == "__main__":
    main()
