"""Converts every WAV under assets/ into C++ sound data the game links in.

The build runs this automatically: save a WAV, rebuild, and it plays.

Naming:
  assets/sounds/steal.wav  ->  sound "sounds/steal"  (a sound effect)
  assets/music/party.wav   ->  sound "music/party"   (a looping track)

Any sample rate, mono or stereo, 8/16/24/32-bit PCM. Everything is mixed down
to mono at 16 kHz, 8-bit -- lo-fi on purpose, so music fits on the handheld.

Usage: python wav2sound.py ASSETS_DIR OUTPUT_CPP
"""

import array
import pathlib
import sys
import wave

RATE = 16000  # must match audio::SAMPLE_RATE


def read_wav(path):
    try:
        with wave.open(str(path), "rb") as w:
            channels, width, rate = w.getnchannels(), w.getsampwidth(), w.getframerate()
            raw = w.readframes(w.getnframes())
    except wave.Error as e:
        sys.exit(f"{path}: can't read it ({e}). Export it as a PCM WAV (16-bit is safest).")

    if width == 1:
        values = [(b - 128) / 128.0 for b in raw]
    elif width == 2:
        a = array.array("h")
        a.frombytes(raw)
        if sys.byteorder == "big":
            a.byteswap()
        values = [v / 32768.0 for v in a]
    elif width == 3:
        values = [int.from_bytes(raw[i:i + 3], "little", signed=True) / 8388608.0 for i in range(0, len(raw), 3)]
    elif width == 4:
        a = array.array("i")
        a.frombytes(raw)
        if sys.byteorder == "big":
            a.byteswap()
        values = [v / 2147483648.0 for v in a]
    else:
        sys.exit(f"{path}: unsupported sample size ({width * 8}-bit)")

    mono = [sum(values[i:i + channels]) / channels for i in range(0, len(values), channels)]
    return mono, rate


def resample(samples, rate):
    if rate == RATE or not samples:
        return samples
    out_len = int(len(samples) * RATE / rate)
    last = len(samples) - 1
    out = []
    for i in range(out_len):
        src = i * rate / RATE
        j = int(src)
        f = src - j
        out.append(samples[j] * (1.0 - f) + samples[min(j + 1, last)] * f)
    return out


def convert(path, root):
    name = path.relative_to(root).with_suffix("").as_posix()
    samples, rate = read_wav(path)
    data = [max(-127, min(127, round(s * 127))) for s in resample(samples, rate)]
    return name, data


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    root = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2])

    sounds = [convert(p, root) for p in sorted(root.rglob("*.wav"))]

    lines = [
        "// Generated by tools/wav2sound.py from assets/. Do not edit.",
        '#include "game/audio.h"',
        "",
        "namespace {",
    ]
    for i, (name, data) in enumerate(sounds):
        lines.append(f"// {name}: {len(data) / RATE:.2f}s")
        lines.append(f"const int8_t SND_{i}[] = {{")
        for row in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(v) for v in data[row:row + 24]) + ",")
        if not data:
            lines.append("    0,")
        lines.append("};")
    lines.append("}  // namespace")
    lines.append("")

    if sounds:
        lines.append("extern const Sound SOUNDS[] = {")
        for i, (name, data) in enumerate(sounds):
            lines.append(f'    {{"{name}", SND_{i}, {len(data)}u}},')
        lines.append("};")
    else:
        lines.append('extern const Sound SOUNDS[] = {{"", nullptr, 0u}};')
    lines.append(f"extern const int SOUND_COUNT = {len(sounds)};")
    text = "\n".join(lines) + "\n"

    # Only touch the file when something changed, so the game doesn't rebuild for nothing.
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    total = sum(len(d) for _, d in sounds)
    print(f"wav2sound: {len(sounds)} sound(s), {total / RATE:.1f}s, {total / 1024:.0f} KB")


if __name__ == "__main__":
    main()
